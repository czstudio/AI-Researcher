#!/usr/bin/env node
// Single source of truth: contracts/*.json -> app/src/lib/modes.generated.js
// Run automatically by `npm run build` in app/.

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const src = path.join(root, 'contracts', 'modes.json');
const out = path.join(root, 'app', 'src', 'lib', 'modes.generated.js');

const modes = JSON.parse(fs.readFileSync(src, 'utf8'));
const banner = `// GENERATED by ops/sync-contracts.mjs from contracts/modes.json — do not edit by hand.\n`;
fs.writeFileSync(out, `${banner}export const MODES = ${JSON.stringify(modes, null, 2)};\nexport default MODES;\n`);
console.log(`[sync-contracts] ${path.relative(root, src)} -> ${path.relative(root, out)} (${modes.modes.length} modes)`);
